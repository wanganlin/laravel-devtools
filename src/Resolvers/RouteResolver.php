<?php

declare(strict_types=1);

namespace Juling\DevTools\Resolvers;

use Illuminate\Support\Arr;
use Illuminate\Support\Str;
use Juling\DevTools\Support\DevConfig;
use Juling\DevTools\Support\SchemaTrait;
use ReflectionClass;
use ReflectionException;
use ReflectionMethod;
use RuntimeException;

class RouteResolver extends Foundation
{
    use SchemaTrait;

    /**
     * @throws ReflectionException
     */
    public function build(DevConfig $devConfig, array $data): void
    {
        $dirs = array_merge(
            glob(app_path('Api/*'), GLOB_ONLYDIR),
            glob(app_path('Domains/*'), GLOB_ONLYDIR),
            glob(app_path('Modules/*'), GLOB_ONLYDIR)
        );
        foreach ($dirs as $dir) {
            $dist = $dir.'/Routes';
            $this->ensureDirectoryExists($dist);

            $controllers = glob($dir.'/Controllers/*Controller.php');
            $routes = $this->getRouteContent($this->getRoutes($controllers));
            file_put_contents($dist.'/route.gen.php', $this->getTemplate($routes));
        }
    }

    /**
     * @throws ReflectionException
     */
    private function getRoutes(array $files): array
    {
        $routes = [];

        $ignoreControllers = config('devtools.exclude_controllers', []);
        foreach ($files as $file) {
            $normalizedFile = str_replace('\\', '/', $file);
            if (! preg_match('/(app\/.+?\/(\w+)Controller)\.php$/i', $normalizedFile, $matches)) {
                continue;
            }

            if (! in_array(Str::studly($matches[2]), $ignoreControllers, true)) {
                // 将相对路径转为标准的 PSR-4 命名空间类名（如 App\Domains\...\...Controller）
                $class = str_replace('/', '\\', ucfirst($matches[1]));
                $classRoutes = $this->reflectionRoutes($class);
                $routes = array_merge($routes, $classRoutes);
            }
        }

        return $routes;
    }

    /**
     * @throws ReflectionException
     */
    private function reflectionRoutes(string $class): array
    {
        $reflectionClass = new ReflectionClass($class);
        $methods = $reflectionClass->getMethods(ReflectionMethod::IS_PUBLIC);
        $methods = array_filter($methods, function ($item) use ($class) {
            return $item->class === $class;
        });

        $validHttpMethods = ['get', 'post', 'put', 'delete', 'patch', 'options', 'head'];
        $routes = [];
        foreach ($methods as $method) {
            foreach ($method->getAttributes() as $attribute) {
                $shortName = Str::lower(Arr::last(explode('\\', $attribute->getName())));
                if (! in_array($shortName, $validHttpMethods, true)) {
                    continue;
                }

                $args = $attribute->getArguments();
                $path = $args['path'] ?? ($args[0] ?? null);
                if (empty($path)) {
                    continue;
                }

                $summary = (string) ($args['summary'] ?? ($args['description'] ?? ''));
                $routes[] = [
                    'httpMethod' => $shortName,
                    'path' => $path === '/' ? $path : ltrim((string) $path, '/'),
                    'class' => $class,
                    'action' => $method->name,
                    'summary' => $summary,
                ];
                break; // 每个方法提取首个有效路由注解
            }
        }

        return $routes;
    }

    private function getRouteContent(array $routes): string
    {
        $routeContent = '';
        foreach ($routes as $route) {
            $routeContent .= "\n// ".$route['summary'];
            $routeContent .= "\nRoute::{$route['httpMethod']}('{$route['path']}', [\\{$route['class']}::class, '{$route['action']}'])";
            if ($route['httpMethod'] === 'get') {
                $name = 'index';
                if ($route['path'] !== '/') {
                    $name = Str::replace('/', '.', $route['path']);
                }
                $routeContent .= "->name('$name')";
            }
            $routeContent .= ';';
        }
        $routeContent .= "\n";

        return $routeContent;
    }

    private function getTemplate($content): string
    {
        return <<<EOF
<?php

// ==========================================================================
// Code generated by gen:route CLI tool. DO NOT EDIT.
// ==========================================================================

declare(strict_types=1);

use Illuminate\Support\Facades\Route;
$content
EOF;
    }
}
